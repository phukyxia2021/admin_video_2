-- ============================================================================
-- SUPABASE SCHEMA FOR VIDEO ADMIN
-- Chạy toàn bộ file SQL này trong Supabase Dashboard -> SQL Editor -> New Query
-- ============================================================================

-- 1. Bảng categories (Danh mục)
CREATE TABLE IF NOT EXISTS public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  slug TEXT NOT NULL UNIQUE,
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Bảng videos (Danh sách video)
CREATE TABLE IF NOT EXISTS public.videos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT,
  thumbnail_url TEXT,
  video_url TEXT,
  category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
  views BIGINT NOT NULL DEFAULT 0 CHECK (views >= 0),
  file_size_bytes BIGINT NOT NULL DEFAULT 0 CHECK (file_size_bytes >= 0),
  status TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('draft', 'published', 'archived')),
  published_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_videos_title ON public.videos(title);
CREATE INDEX IF NOT EXISTS idx_videos_views ON public.videos(views DESC);
CREATE INDEX IF NOT EXISTS idx_videos_category ON public.videos(category_id);

-- 3. Bảng tags & video_tag_map
CREATE TABLE IF NOT EXISTS public.tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.video_tag_map (
  video_id BIGINT REFERENCES public.videos(id) ON DELETE CASCADE,
  tag_id BIGINT REFERENCES public.tags(id) ON DELETE CASCADE,
  PRIMARY KEY (video_id, tag_id)
);

-- 4. Bảng video_views_daily (Thống kê lượt xem theo ngày)
CREATE TABLE IF NOT EXISTS public.video_views_daily (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  video_id BIGINT REFERENCES public.videos(id) ON DELETE CASCADE,
  view_date DATE NOT NULL,
  views BIGINT NOT NULL DEFAULT 0 CHECK (views >= 0),
  UNIQUE(video_id, view_date)
);

CREATE INDEX IF NOT EXISTS idx_analytics_date ON public.video_views_daily(view_date);
CREATE INDEX IF NOT EXISTS idx_analytics_video ON public.video_views_daily(video_id);

-- 5. Bảng app_users (Tài khoản người dùng & phân quyền)
CREATE TABLE IF NOT EXISTS public.app_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'USER' CHECK (role IN ('ADMIN', 'USER')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_users_email ON public.app_users(email);
CREATE INDEX IF NOT EXISTS idx_users_role ON public.app_users(role);

-- ============================================================================
-- KÍCH HOẠT ROW LEVEL SECURITY (RLS) VÀ CẤP QUYỀN TRUY CẬP CHO ANON ROLE
-- ============================================================================
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.videos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tags ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.video_tag_map ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.video_views_daily ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_users ENABLE ROW LEVEL SECURITY;

-- Cấp quyền SELECT, INSERT, UPDATE, DELETE cho anon role (frontend client)
DROP POLICY IF EXISTS "Allow anon full access categories" ON public.categories;
CREATE POLICY "Allow anon full access categories" ON public.categories FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon full access videos" ON public.videos;
CREATE POLICY "Allow anon full access videos" ON public.videos FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon full access tags" ON public.tags;
CREATE POLICY "Allow anon full access tags" ON public.tags FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon full access video_tag_map" ON public.video_tag_map;
CREATE POLICY "Allow anon full access video_tag_map" ON public.video_tag_map FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon full access video_views_daily" ON public.video_views_daily;
CREATE POLICY "Allow anon full access video_views_daily" ON public.video_views_daily FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon full access app_users" ON public.app_users;
CREATE POLICY "Allow anon full access app_users" ON public.app_users FOR ALL USING (true) WITH CHECK (true);

